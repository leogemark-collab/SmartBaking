import { Head } from '@inertiajs/react';
import {
    ArrowRight,
    CalendarDays,
    Clock3,
    Info,
    Layers3,
    PackageSearch,
    Sparkles,
} from 'lucide-react';
import { useState } from 'react';
import {
    Area,
    CartesianGrid,
    ComposedChart,
    Line,
    ResponsiveContainer,
    Tooltip,
    XAxis,
    YAxis,
} from 'recharts';
import { Button } from '@/components/ui/button';
import {
    Field,
    PageHeading,
    Panel,
    StatCard,
    StatusBadge,
} from '@/components/workspace/ui';
import { useWorkspace } from '@/components/workspace/workspace-provider';
import { branches } from '@/lib/workspace';

const products = [
    { id: 'pandesal', name: 'Classic pandesal', factor: 1 },
    { id: 'spanish-bread', name: 'Spanish bread', factor: 0.61 },
    { id: 'ensaymada', name: 'Cheese ensaymada', factor: 0.32 },
];

const dayProfiles = [
    { label: 'Thu 12', date: '12 Nov', base: 740 },
    { label: 'Fri 13', date: '13 Nov', base: 790 },
    { label: 'Sat 14', date: '14 Nov', base: 925 },
    { label: 'Sun 15', date: '15 Nov', base: 985 },
    { label: 'Mon 16', date: '16 Nov', base: 760 },
    { label: 'Tue 17', date: '17 Nov', base: 705 },
    { label: 'Wed 18', date: '18 Nov', base: 750 },
];

const hourShares = [
    0.1, 0.15, 0.14, 0.1, 0.07, 0.06, 0.05, 0.06, 0.07, 0.06, 0.05, 0.04, 0.03,
    0.02,
];
const ingredientDays = [
    { date: 'Thu, 12 Nov', opening: 75, production: 22, closing: 53 },
    { date: 'Fri, 13 Nov', opening: 53, production: 26, closing: 27 },
    { date: 'Sat, 14 Nov', opening: 27, production: 29, closing: -2 },
];

export default function Forecasts() {
    const { branch } = useWorkspace();
    const [frequency, setFrequency] = useState<'daily' | 'hourly'>('daily');
    const [productId, setProductId] = useState('pandesal');
    const [holiday, setHoliday] = useState(true);
    const [payday, setPayday] = useState(true);
    const product =
        products.find((item) => item.id === productId) ?? products[0];
    const branchFactor =
        [1, 0.88, 0.76][Math.max(0, branches.indexOf(branch))] ?? 1;

    const daily = dayProfiles.map((day, index) => {
        const reference = Math.round(day.base * product.factor * branchFactor);
        const holidayEffect = holiday && index === 3 ? 1.12 : 1;
        const paydayEffect = payday && index >= 2 && index <= 4 ? 1.08 : 1;
        return {
            ...day,
            reference,
            projected: Math.round(reference * holidayEffect * paydayEffect),
        };
    });
    let allocatedProjection = 0;
    let allocatedReference = 0;
    const hourly = hourShares.map((share, index) => {
        const projected =
            index === hourShares.length - 1
                ? daily[3].projected - allocatedProjection
                : Math.round(daily[3].projected * share);
        const reference =
            index === hourShares.length - 1
                ? daily[3].reference - allocatedReference
                : Math.round(daily[3].reference * share);
        allocatedProjection += projected;
        allocatedReference += reference;
        const hour = index + 5;
        return {
            label: `${hour.toString().padStart(2, '0')}:00`,
            date: `15 Nov, ${hour.toString().padStart(2, '0')}:00–${(hour + 1).toString().padStart(2, '0')}:00`,
            reference,
            projected,
        };
    });
    const chart = frequency === 'daily' ? daily : hourly;
    const total = daily.reduce((sum, day) => sum + day.projected, 0);
    const peak = chart.reduce((highest, point) =>
        point.projected > highest.projected ? point : highest,
    );
    const calendarLabel = `${holiday ? 'Holiday on' : 'Holiday off'} · ${payday ? 'Payday on' : 'Payday off'}`;

    return (
        <>
            <Head title="Forecasts" />
            <div className="space-y-7">
                <PageHeading
                    eyebrow="DEMAND & PLANNING"
                    title="A little clarity for the next bake."
                    description={`Explore an illustrative outlook for ${branch}. These sample values are not generated by a trained model.`}
                    actions={
                        <StatusBadge tone="terra">
                            <Sparkles className="size-3.5" aria-hidden="true" />{' '}
                            Scenario preview
                        </StatusBadge>
                    }
                />

                <div className="flex flex-wrap items-center justify-between gap-4 rounded-xl border border-[#e9e4dc] bg-[#faf8f4] px-5 py-4 text-sm">
                    <div className="flex items-start gap-3 text-[#70675e]">
                        <Info
                            className="mt-0.5 size-4 shrink-0 text-[#a6533b]"
                            aria-hidden="true"
                        />
                        <p>
                            <span className="font-medium text-[#332c25]">
                                Model not connected.
                            </span>{' '}
                            SARIMAX is the proposed daily-model scenario.
                            Controls only change the local illustration.
                        </p>
                    </div>
                    <span className="shrink-0 text-xs text-[#70675e]">
                        Sample issue · 11 Nov 2026, 05:30 PHT
                    </span>
                </div>

                <div className="grid gap-4 sm:grid-cols-3">
                    <StatCard
                        label="7-day illustrative demand"
                        value={`${total.toLocaleString()} pcs`}
                        hint={`${product.name} · 12–18 Nov 2026`}
                        icon={Layers3}
                    />
                    <StatCard
                        label={
                            frequency === 'daily'
                                ? 'Highest projected day'
                                : 'Highest projected hour'
                        }
                        value={peak.label}
                        hint={`${peak.projected.toLocaleString()} pieces · sample projection`}
                        icon={Clock3}
                    />
                    <StatCard
                        label="Planning horizon"
                        value="7 days"
                        hint="Daily outlook + hourly allocation"
                        icon={CalendarDays}
                    />
                </div>

                <Panel
                    title="Sales outlook"
                    description="Illustrative product quantities, in pieces. Calendar effects are hypothetical inputs."
                >
                    <div className="px-5 pb-5 sm:px-6 sm:pb-6">
                        <div className="flex flex-wrap items-end justify-between gap-5 border-b border-[#e9e4dc] pb-5">
                            <div className="flex flex-wrap items-end gap-4">
                                <Field label="Product">
                                    <select
                                        aria-label="Forecast product"
                                        value={productId}
                                        onChange={(event) =>
                                            setProductId(event.target.value)
                                        }
                                        className="h-10 min-w-44 rounded-lg border border-[#e2dcd3] bg-white px-3 text-sm text-[#332c25] outline-none focus-visible:ring-2 focus-visible:ring-[#a6533b]/40"
                                    >
                                        {products.map((item) => (
                                            <option
                                                key={item.id}
                                                value={item.id}
                                            >
                                                {item.name}
                                            </option>
                                        ))}
                                    </select>
                                </Field>
                                <div
                                    role="group"
                                    aria-label="Forecast time interval"
                                    className="flex rounded-lg border border-[#e9e4dc] bg-[#f8f6f2] p-1"
                                >
                                    {(['daily', 'hourly'] as const).map(
                                        (interval) => (
                                            <button
                                                key={interval}
                                                type="button"
                                                aria-pressed={
                                                    frequency === interval
                                                }
                                                onClick={() =>
                                                    setFrequency(interval)
                                                }
                                                className={`rounded-md px-4 py-2 text-sm font-medium capitalize transition focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#a6533b] ${frequency === interval ? 'bg-white text-[#a6533b] shadow-sm' : 'text-[#70675e] hover:text-[#332c25]'}`}
                                            >
                                                {interval}
                                            </button>
                                        ),
                                    )}
                                </div>
                            </div>
                            <div
                                className="flex flex-wrap gap-2"
                                role="group"
                                aria-label="Illustrative calendar effects"
                            >
                                <Button
                                    variant="outline"
                                    aria-pressed={holiday}
                                    onClick={() => setHoliday(!holiday)}
                                    className={
                                        holiday
                                            ? 'border-[#d7b5a8] bg-[#f7eee9] text-[#93432f]'
                                            : ''
                                    }
                                >
                                    <CalendarDays /> Holiday{' '}
                                    {holiday ? 'on' : 'off'}
                                </Button>
                                <Button
                                    variant="outline"
                                    aria-pressed={payday}
                                    onClick={() => setPayday(!payday)}
                                    className={
                                        payday
                                            ? 'border-[#cbd4c5] bg-[#eff2ec] text-[#526449]'
                                            : ''
                                    }
                                >
                                    Payday {payday ? 'on' : 'off'}
                                </Button>
                            </div>
                        </div>

                        <div className="flex flex-wrap items-center justify-between gap-3 pt-5">
                            <div>
                                <h3 className="text-sm font-semibold text-[#332c25]">
                                    {product.name} ·{' '}
                                    {frequency === 'daily'
                                        ? '12–18 November'
                                        : 'Sunday, 15 November'}
                                </h3>
                                <p
                                    className="mt-1 text-xs text-[#70675e]"
                                    aria-live="polite"
                                >
                                    Illustrative SARIMAX scenario ·{' '}
                                    {calendarLabel} · {branch}
                                </p>
                            </div>
                            <div className="flex gap-4 text-xs text-[#70675e]">
                                <span className="flex items-center gap-2">
                                    <span className="h-0.5 w-4 rounded bg-[#a6533b]" />{' '}
                                    Projection
                                </span>
                                <span className="flex items-center gap-2">
                                    <span className="w-4 border-t-2 border-dashed border-[#73836d]" />{' '}
                                    Reference profile
                                </span>
                            </div>
                        </div>
                        <p className="sr-only">
                            {frequency === 'daily'
                                ? `Seven-day sample total: ${total} pieces.`
                                : `Hourly allocations sum to ${daily[3].projected} pieces for 15 November.`}{' '}
                            Highest interval: {peak.label}, {peak.projected}{' '}
                            pieces. Exact values follow in the expandable table.
                        </p>
                        <div className="mt-5 h-72 w-full min-w-0 sm:h-80">
                            <ResponsiveContainer width="100%" height="100%">
                                <ComposedChart
                                    accessibilityLayer
                                    data={chart}
                                    margin={{
                                        top: 10,
                                        right: 10,
                                        left: -20,
                                        bottom: 0,
                                    }}
                                >
                                    <defs>
                                        <linearGradient
                                            id="forecast-terra-fill"
                                            x1="0"
                                            y1="0"
                                            x2="0"
                                            y2="1"
                                        >
                                            <stop
                                                offset="0%"
                                                stopColor="#a6533b"
                                                stopOpacity={0.17}
                                            />
                                            <stop
                                                offset="100%"
                                                stopColor="#a6533b"
                                                stopOpacity={0.01}
                                            />
                                        </linearGradient>
                                    </defs>
                                    <CartesianGrid
                                        stroke="#eee9e1"
                                        vertical={false}
                                        strokeDasharray="3 4"
                                    />
                                    <XAxis
                                        dataKey="label"
                                        tickLine={false}
                                        axisLine={false}
                                        tick={{ fill: '#756b61', fontSize: 11 }}
                                        minTickGap={22}
                                        dy={10}
                                    />
                                    <YAxis
                                        tickLine={false}
                                        axisLine={false}
                                        tick={{ fill: '#756b61', fontSize: 11 }}
                                    />
                                    <Tooltip
                                        contentStyle={{
                                            borderColor: '#e9e4dc',
                                            borderRadius: 12,
                                            fontSize: 12,
                                        }}
                                    />
                                    <Area
                                        name="Illustrative projection (pcs)"
                                        type="monotone"
                                        dataKey="projected"
                                        stroke="#a6533b"
                                        strokeWidth={2.5}
                                        fill="url(#forecast-terra-fill)"
                                        isAnimationActive={false}
                                    />
                                    <Line
                                        name="Reference profile (pcs)"
                                        type="monotone"
                                        dataKey="reference"
                                        stroke="#73836d"
                                        strokeWidth={1.8}
                                        strokeDasharray="5 5"
                                        dot={false}
                                        isAnimationActive={false}
                                    />
                                </ComposedChart>
                            </ResponsiveContainer>
                        </div>
                        <div className="mt-5 flex flex-wrap gap-x-6 gap-y-2 rounded-lg bg-[#faf8f4] px-4 py-3 text-xs text-[#70675e]">
                            <span>
                                Hypothetical holiday:{' '}
                                <strong className="font-medium text-[#332c25]">
                                    15 Nov
                                </strong>
                            </span>
                            <span>
                                Assumed payday window:{' '}
                                <strong className="font-medium text-[#332c25]">
                                    14–16 Nov
                                </strong>
                            </span>
                            <span>
                                {frequency === 'hourly'
                                    ? 'Hourly shares reconcile to the sample daily total.'
                                    : 'Scenario multipliers demonstrate controls; they are not learned effects.'}
                            </span>
                        </div>
                        <details className="mt-4 text-sm">
                            <summary className="cursor-pointer py-2 font-medium text-[#a6533b] focus-visible:outline-2 focus-visible:outline-offset-2">
                                View projection values
                            </summary>
                            <div className="mt-2 overflow-x-auto">
                                <table className="w-full min-w-96 text-left text-xs">
                                    <caption className="sr-only">
                                        Synthetic {frequency} quantities for{' '}
                                        {product.name}, {branch}, PHT.
                                    </caption>
                                    <thead className="border-b border-[#e9e4dc] text-[#70675e]">
                                        <tr>
                                            <th
                                                scope="col"
                                                className="py-3 font-medium"
                                            >
                                                {frequency === 'daily'
                                                    ? 'Date (2026, PHT)'
                                                    : 'Hour (2026, PHT)'}
                                            </th>
                                            <th
                                                scope="col"
                                                className="py-3 text-right font-medium"
                                            >
                                                Reference (pcs)
                                            </th>
                                            <th
                                                scope="col"
                                                className="py-3 text-right font-medium"
                                            >
                                                Projection (pcs)
                                            </th>
                                        </tr>
                                    </thead>
                                    <tbody>
                                        {chart.map((point) => (
                                            <tr
                                                key={point.label}
                                                className="border-b border-[#f0ece6]"
                                            >
                                                <th
                                                    scope="row"
                                                    className="py-3 font-medium text-[#332c25]"
                                                >
                                                    {point.date}
                                                </th>
                                                <td className="py-3 text-right text-[#70675e] tabular-nums">
                                                    {point.reference.toLocaleString()}
                                                </td>
                                                <td className="py-3 text-right font-medium text-[#a6533b] tabular-nums">
                                                    {point.projected.toLocaleString()}
                                                </td>
                                            </tr>
                                        ))}
                                    </tbody>
                                </table>
                            </div>
                        </details>
                    </div>
                </Panel>

                <div className="grid items-start gap-5 xl:grid-cols-[1.5fr_1fr]">
                    <Panel
                        title="From the bake plan to ingredient needs"
                        description="Independent, branch-neutral flour example · no incoming deliveries · sample production plan."
                    >
                        <div className="px-5 pb-5 sm:px-6 sm:pb-6">
                            <div className="mb-5 grid grid-cols-3 gap-3 rounded-xl bg-[#faf8f4] p-4">
                                <div>
                                    <p className="text-xs text-[#756b61]">
                                        Usable flour
                                    </p>
                                    <p className="mt-1 text-lg font-semibold text-[#332c25]">
                                        75{' '}
                                        <span className="text-xs font-normal">
                                            kg
                                        </span>
                                    </p>
                                </div>
                                <div>
                                    <p className="text-xs text-[#756b61]">
                                        Supplier lead time
                                    </p>
                                    <p className="mt-1 text-lg font-semibold text-[#332c25]">
                                        2{' '}
                                        <span className="text-xs font-normal">
                                            days
                                        </span>
                                    </p>
                                </div>
                                <div>
                                    <p className="text-xs text-[#756b61]">
                                        Safety stock
                                    </p>
                                    <p className="mt-1 text-lg font-semibold text-[#332c25]">
                                        10{' '}
                                        <span className="text-xs font-normal">
                                            kg
                                        </span>
                                    </p>
                                </div>
                            </div>
                            <div className="overflow-x-auto">
                                <table className="w-full min-w-96 text-left text-xs">
                                    <caption className="sr-only">
                                        Independent synthetic ingredient
                                        balance, kilograms, November 2026 PHT.
                                        Negative balance represents unmet
                                        requirements, not physical negative
                                        stock.
                                    </caption>
                                    <thead className="border-b border-[#e9e4dc] text-[#756b61]">
                                        <tr>
                                            <th
                                                scope="col"
                                                className="pb-3 font-medium"
                                            >
                                                Production date
                                            </th>
                                            <th
                                                scope="col"
                                                className="pb-3 text-right font-medium"
                                            >
                                                Opening
                                            </th>
                                            <th
                                                scope="col"
                                                className="pb-3 text-right font-medium"
                                            >
                                                Batch needs
                                            </th>
                                            <th
                                                scope="col"
                                                className="pb-3 text-right font-medium"
                                            >
                                                Projected balance
                                            </th>
                                        </tr>
                                    </thead>
                                    <tbody>
                                        {ingredientDays.map((day) => (
                                            <tr
                                                key={day.date}
                                                className="border-b border-[#f0ece6]"
                                            >
                                                <th
                                                    scope="row"
                                                    className="py-4 font-medium text-[#332c25]"
                                                >
                                                    {day.date}
                                                </th>
                                                <td className="py-4 text-right tabular-nums">
                                                    {day.opening} kg
                                                </td>
                                                <td className="py-4 text-right tabular-nums">
                                                    −{day.production} kg
                                                </td>
                                                <td
                                                    className={`py-4 text-right font-medium tabular-nums ${day.closing < 0 ? 'text-[#a6533b]' : 'text-[#526449]'}`}
                                                >
                                                    {day.closing} kg
                                                </td>
                                            </tr>
                                        ))}
                                    </tbody>
                                </table>
                            </div>
                            <p className="mt-4 text-xs leading-relaxed text-[#756b61]">
                                Recipe requirements consume ingredients at
                                production time. A negative projected balance
                                indicates unmet requirements; it is not recorded
                                stock. This independent example does not change
                                with the sales-chart controls.
                            </p>
                        </div>
                    </Panel>

                    <div className="space-y-4">
                        <div className="rounded-2xl border border-[#e4d4bc] bg-[#fbf5e9] p-6">
                            <div className="flex size-10 items-center justify-center rounded-xl bg-[#f1e6ce] text-[#8e682c]">
                                <PackageSearch
                                    className="size-5"
                                    aria-hidden="true"
                                />
                            </div>
                            <p className="mt-4 text-xs font-medium tracking-wide text-[#8e682c]">
                                ILLUSTRATIVE REORDER ADVISORY
                            </p>
                            <h3 className="mt-2 text-xl font-semibold tracking-tight text-[#332c25]">
                                Review a flour order by 12 Nov.
                            </h3>
                            <p className="mt-3 text-sm leading-relaxed text-[#70675e]">
                                The sample plan becomes 2 kg short on 14 Nov.
                                With a two-day supplier lead time, review an
                                order by 12 Nov for arrival before production.
                            </p>
                            <div className="mt-5 flex items-center gap-2 text-xs font-medium text-[#8e682c]">
                                <span>Projected balance</span>
                                <ArrowRight className="size-3" />
                                <span>Lead time</span>
                                <ArrowRight className="size-3" />
                                <span>Order date</span>
                            </div>
                            <p className="mt-4 border-t border-[#e8dcc6] pt-4 text-xs leading-relaxed text-[#81705a]">
                                Delivery timing, later batches, safety stock,
                                expiry and pack sizes would determine the final
                                order quantity. No purchase order is created.
                            </p>
                        </div>
                        <div className="rounded-xl border border-[#e9e4dc] bg-white p-5 text-xs leading-relaxed text-[#756b61]">
                            <p className="font-semibold text-[#332c25]">
                                What happens when real data is connected?
                            </p>
                            <p className="mt-2">
                                Evaluate SARIMAX and LightGBM against a
                                same-weekday baseline. Allocate daily demand
                                into hourly profiles, then convert approved
                                baking plans into recipe-based ingredient needs.
                            </p>
                        </div>
                    </div>
                </div>
            </div>
        </>
    );
}
